// Point-in-time feature construction.
//
// THE WHOLE POINT OF THIS FILE: every feature attached to a fixture is computed
// only from matches that finished strictly BEFORE that fixture kicked off.
//
// This is what the live site's current model does not do. `golden server.js`
// scores historical fixtures using `seasonOver25PercentageHT_overall` and
// friends, which FootyStats computes across the whole season — including the
// match being predicted. Any backtest built that way leaks the answer into the
// features and reports lift that will not survive contact with a real slate.
// If the quoted 2.76x / 2.65x lifts came from that setup, treat them as unproven.

import { mean, noVig3 } from './stats.js';

const tail = (arr, n) => (n >= arr.length ? arr : arr.slice(arr.length - n));

// Shrink a small-sample team rate toward the league's per-team average.
// With 6-10 prior matches the raw rate is mostly noise; k=5 pseudo-matches of
// league-average prior is a reasonable default (tune with --shrink).
function shrunkRate(values, prior, k) {
  const sum = values.reduce((s, x) => s + x, 0);
  return (sum + k * prior) / (values.length + k);
}

function teamState(map, name) {
  let s = map.get(name);
  if (!s) { s = { home: [], away: [] }; map.set(name, s); }
  return s;
}

/**
 * @param {Array} matches normalised match objects:
 *   { date, league, home, away, hc, ac, odds?: {h,d,a} }
 *   where hc/ac are home/away corner counts.
 * @returns {Array} feature rows, chronological.
 */
export function buildDataset(matches, opts = {}) {
  const {
    window = 10,      // rolling matches per team per venue
    minPrior = 6,     // burn-in: prior matches required in that venue
    shrink = 5,       // pseudo-matches of league-average prior
    leagueWindow = 200,
    minLeaguePrior = 30,
  } = opts;

  const sorted = matches
    .filter(m => Number.isFinite(m.hc) && Number.isFinite(m.ac) && Number.isFinite(m.date))
    .sort((a, b) => a.date - b.date);

  const teams = new Map();
  const leagues = new Map();
  const rows = [];
  let skippedBurnIn = 0;

  for (const m of sorted) {
    const ht = teamState(teams, m.home);
    const at = teamState(teams, m.away);
    const lgHist = leagues.get(m.league) ?? [];

    const enoughTeam = ht.home.length >= minPrior && at.away.length >= minPrior;
    const enoughLeague = lgHist.length >= minLeaguePrior;

    if (enoughTeam && enoughLeague) {
      rows.push(makeRow(m, ht, at, lgHist, { window, shrink, leagueWindow }));
    } else {
      skippedBurnIn++;
    }

    // State update happens only AFTER the row is emitted.
    ht.home.push({ cf: m.hc, ca: m.ac });
    at.away.push({ cf: m.ac, ca: m.hc });
    lgHist.push({ h: m.hc, a: m.ac });
    leagues.set(m.league, lgHist);
  }

  rows.skippedBurnIn = skippedBurnIn;
  return rows;
}

function makeRow(m, ht, at, lgHist, { window, shrink, leagueWindow }) {
  const lgWin = tail(lgHist, leagueWindow);
  const lgHC = mean(lgWin.map(x => x.h)); // league mean corners won by the home side
  const lgAC = mean(lgWin.map(x => x.a)); // ... by the away side
  const lgMean = lgHC + lgAC;

  const hHome = tail(ht.home, window);
  const aAway = tail(at.away, window);

  // Venue-specific rates, shrunk toward the venue-appropriate league prior.
  // A home team's corners-for and an away team's corners-against are draws from
  // the same population (home-side corners), so they share the lgHC prior.
  const hCF = shrunkRate(hHome.map(x => x.cf), lgHC, shrink);
  const hCA = shrunkRate(hHome.map(x => x.ca), lgAC, shrink);
  const aCF = shrunkRate(aAway.map(x => x.cf), lgAC, shrink);
  const aCA = shrunkRate(aAway.map(x => x.ca), lgHC, shrink);

  // Attack index x defence index x league mean — the Dixon-Coles form.
  //
  // NOT the arithmetic mean of the two rates. Averaging two absolute rates
  // silently halves the signal: each rate already contains one league-average
  // term, so (hCF + aCA)/2 lands exactly halfway between the true expectation
  // and the league mean. The self-test caught this; the multiplicative form
  // recovers full amplitude. `baselineAdditive` is kept only to show the gap.
  const expHome = (hCF * aCA) / Math.max(lgHC, 0.1);
  const expAway = (aCF * hCA) / Math.max(lgAC, 0.1);
  const baseline = expHome + expAway;
  const baselineAdditive = (hCF + aCA) / 2 + (aCF + hCA) / 2;

  // Mismatch: corners are generated by a favourite camped against a low block,
  // so pre-match price dispersion is the natural territorial-dominance proxy.
  const nv = m.odds ? noVig3(m.odds.h, m.odds.d, m.odds.a) : null;
  const mismatch = nv ? Math.abs(nv.home - nv.away) : null;
  const favIsHome = nv ? nv.home >= nv.away : null;

  // Style proxy: a side that concedes a lot of corners is defending deep —
  // the classic corner-inflating shape.
  const blockiness = (hCA / Math.max(lgAC, 0.1) + aCA / Math.max(lgHC, 0.1)) / 2;

  return {
    date: m.date,
    league: m.league,
    home: m.home,
    away: m.away,
    // features
    hCF, hCA, aCF, aCA,
    expHome, expAway, baseline, baselineAdditive,
    lgMean, lgHC, lgAC, mismatch, favIsHome, blockiness,
    nPriorHome: ht.home.length,
    nPriorAway: at.away.length,
    // outcomes (never used as features)
    actualHome: m.hc,
    actualAway: m.ac,
    actual: m.hc + m.ac,
    actualFav: favIsHome === null ? null : (favIsHome ? m.hc : m.ac),
  };
}
